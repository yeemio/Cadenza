/** 从服务端 message 提取 P2 规则号：`[RS-01]`/`[FC-05]`/`[WR-24]`/`[QD-08]`/`[MT-10]`/`[RP-03]`；无则 null。 */
export function p2RuleCodeOf(message: string | undefined | null): string | null {
  if (!message) return null
  const m = /\[((?:RS|FC|WR|QD|MT|RP)-\d+)\]/.exec(message)
  return m ? m[0].slice(1, -1) : null
}

/**
 * 组装 PC-14 口径错误展示（P2 版）：
 * P2 规则码优先（本表可行动文案为主文案）；未命中回退既有 formatErrorTitleAndDetail
 * （P1 平台 7 码 + MD/IT/OA/A 系规则码，行为不回归）。服务端原始 message 始终并入 detail。
 */
export function formatP2ErrorTitleAndDetail(err: {
  code?: string
  message?: string
  requestId?: string
}): { title: string; detail?: string } {
  const rule = p2RuleCodeOf(err.message)
  const table = getGlobalLocale() === 'ko-KR' ? P2_RULE_MESSAGES_KO : P2_RULE_MESSAGES_ZH
  if (rule !== null && table[rule]) {
    const title = table[rule]!
    const parts: string[] = []
    if (err.message && err.message !== title) parts.push(err.message)
    if (err.requestId) parts.push(t('请求标识：{p0}', { p0: err.requestId }))
    return { title, detail: parts.length > 0 ? parts.join('；') : undefined }
  }
  return formatErrorTitleAndDetail(err)
}
