/**
 * 从服务端 message 提取 P3 规则码：覆盖 `[OT-25]`/`[PE-04]`/`[CS-19]`/`[CE-03]`；
 * 无则 null。
 */
export function p3RuleCodeOf(message: string | undefined | null): string | null {
  if (!message) return null
  const m = /\[((?:OT|PE|CS|CE)(?:-\d+)+)\]/.exec(message)
  return m ? m[0].slice(1, -1) : null
}

/**
 * 组装 P3 错误展示（PC-14 口径）：规则码已收录 → 可行动中文指引为主文案，
 * 服务端原文与规则码并入 detail；未收录 → 回退既有 formatErrorTitleAndDetail。
 */
export function formatP3Error(err: {
  code?: string
  message?: string
  requestId?: string
}): { title: string; detail?: string } {
  const rule = p3RuleCodeOf(err.message)
  const table = getGlobalLocale() === 'ko-KR' ? P3_RULE_MESSAGES_KO : P3_RULE_MESSAGES_ZH
  if (rule !== null && table[rule]) {
    const parts: string[] = []
    if (err.message) parts.push(err.message)
    if (err.requestId) parts.push(t('请求标识：{p0}', { p0: err.requestId }))
    return { title: table[rule], detail: parts.length > 0 ? parts.join('；') : undefined }
  }
  return formatErrorTitleAndDetail(err)
}
